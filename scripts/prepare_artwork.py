"""Deterministically resize supplied SVG images; no replacement artwork or source edits."""

import argparse
import base64
import hashlib
import json
import subprocess
from io import BytesIO
from pathlib import Path
from xml.etree import ElementTree as ET

from PIL import Image, __version__, features

ROOT = Path(__file__).resolve().parents[1]
# Whole source images are preserved; CSS retains the original display cropping.
SPECS = {
    "background": ("image0_0_1", (1600, 2400)),
    "masthead": ("image2_0_1", (740,)),
    "india": ("image3_0_1", (48, 96)),
    "world": ("image4_0_1", (48, 96)),
    "trade": ("image5_0_1", (192, 384)),
    "inflation": ("image6_0_1", (96, 192)),
    "target": ("image7_0_1", (192, 384)),
    "us": ("image8_0_1", (48, 96)),
    "gst": ("image9_0_1", (96, 192)),
    "gst-average": ("image10_0_1", (96, 192)),
    "expenditure": ("image11_0_1", (192, 384)),
}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def prepare(svg_path):
    raw = svg_path.read_bytes()
    svg = ET.fromstring(raw)
    images = {
        n.get("id"): base64.b64decode(n.get("{http://www.w3.org/1999/xlink}href").split(",", 1)[1])
        for n in svg.iter()
        if n.tag.endswith("image")
    }
    output = ROOT / "frontend/public/design"
    assets = []
    for name, (identity, widths) in SPECS.items():
        source = images[identity]
        image = Image.open(BytesIO(source)).convert("RGBA")
        variants = []
        for width in widths:
            size = (width, round(image.height * width / image.width))
            resized = image if image.size == size else image.resize(size, Image.Resampling.LANCZOS)
            encoded = BytesIO()
            resized.save(encoded, format="WEBP", lossless=True, exact=True, method=6)
            data = encoded.getvalue()
            sha = digest(data)
            path = output / f"{name}-{width}-{sha[:12]}.webp"
            path.write_bytes(data)
            variants.append(
                {
                    "file": str(path.relative_to(ROOT)),
                    "width": width,
                    "height": size[1],
                    "byte_length": len(data),
                    "sha256": sha,
                }
            )
        assets.append(
            {
                "name": name,
                "id": identity,
                "source_width": image.width,
                "source_height": image.height,
                "source_sha256": digest(source),
                "variants": variants,
            }
        )
    manifest = {
        "source_svg_sha256": digest(raw),
        "source_dimensions": [svg.get("width"), svg.get("height")],
        "pillow": __version__,
        "libwebp": features.version("webp"),
        "encoding": "RGBA; proportional LANCZOS; lossless WebP exact=True method=6; no crop",
        "assets": assets,
    }
    (output / "assets.json").write_text(json.dumps(manifest, indent=2) + "\n")
    keep = {v["file"].split("/")[-1] for a in assets for v in a["variants"]}
    for path in output.glob("*.webp"):
        if path.name not in keep:
            path.unlink()
    artwork = {}
    for asset in assets:
        variants = asset["variants"]
        artwork[asset["name"]] = {
            "src": "/design/" + Path(variants[0]["file"]).name,
            "srcSet": ", ".join(f"/design/{Path(v['file']).name} {i + 1}x" for i, v in enumerate(variants)),
            "width": variants[0]["width"],
            "height": variants[0]["height"],
        }
    (ROOT / "frontend/src/artwork.ts").write_text(
        "// Generated by scripts/prepare_artwork.py from the supplied SVG.\n"
        + "export const artwork: Record<string, {src: string; srcSet: string; width: number; height: number}> = "
        + json.dumps(artwork, indent=2)
        + ";\n"
    )
    css = "/* Generated by scripts/prepare_artwork.py; original whole-image crops remain in styles.css. */\n:root {\n"
    for name in ("background", "masthead"):
        css += (
            f"  --{name}-image: image-set("
            + ", ".join(
                f"url('/design/{Path(v['file']).name}') {i + 1}x"
                for i, v in enumerate(next(a for a in assets if a["name"] == name)["variants"])
            )
            + ");\n"
        )
    (ROOT / "frontend/src/artwork.css").write_text(css + "}\n")
    subprocess.run(
        [
            str(ROOT / "frontend/node_modules/.bin/prettier"),
            "--write",
            str(ROOT / "frontend/src/artwork.ts"),
            str(ROOT / "frontend/src/artwork.css"),
        ],
        check=True,
    )
    print(
        f"Prepared {len(keep)} variants: {sum(v['byte_length'] for a in assets for v in a['variants']):,} bytes"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("svg", type=Path)
    prepare(parser.parse_args().svg)
