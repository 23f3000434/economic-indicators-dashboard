-- PostgreSQL equivalent of the existing SQLite v4 canonical/auth schema.
CREATE TABLE observations (
 series_id TEXT NOT NULL, period_key TEXT NOT NULL, value TEXT NOT NULL,
 provider_status TEXT NOT NULL, footnote TEXT NOT NULL, source_url TEXT NOT NULL,
 dataset_updated_on TEXT, retrieved_at TEXT NOT NULL, response_sha256 TEXT NOT NULL,
 retained SMALLINT NOT NULL DEFAULT 0 CHECK(retained IN (0,1)),
 group_id TEXT NOT NULL DEFAULT 'gdp',
 measurement_json TEXT CHECK(measurement_json IS NULL OR jsonb_typeof(measurement_json::jsonb)='object'),
 PRIMARY KEY(series_id,period_key)
);
CREATE INDEX observations_group ON observations(group_id,period_key);
CREATE TABLE collection_runs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id TEXT NOT NULL, attempted_at TEXT NOT NULL, completed_at TEXT,
 outcome TEXT NOT NULL CHECK(outcome IN ('running','ok','error')), error_kind TEXT,
 window_start INTEGER NOT NULL, window_end INTEGER NOT NULL,
 provider_id TEXT NOT NULL DEFAULT 'world_bank_wdi', owner_token TEXT
);
CREATE INDEX collection_group_time ON collection_runs(group_id,id DESC);
CREATE UNIQUE INDEX one_running_group ON collection_runs(group_id) WHERE outcome='running';
CREATE TABLE provider_cooldowns (provider_id TEXT PRIMARY KEY,not_before DOUBLE PRECISION NOT NULL,reason TEXT NOT NULL);
CREATE TABLE users (id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL,active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)));
CREATE TABLE sessions (
 id TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),created_at BIGINT NOT NULL,
 expires_at BIGINT NOT NULL,revoked_at BIGINT,confirmed_at BIGINT
);
CREATE INDEX session_expiry ON sessions(expires_at);
CREATE TABLE refresh_tokens (
 digest TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
 state TEXT NOT NULL CHECK(state IN ('active','pending','retired')), created_at BIGINT NOT NULL,retired_at BIGINT
);
CREATE UNIQUE INDEX one_active_token ON refresh_tokens(session_id) WHERE state='active';
CREATE UNIQUE INDEX one_pending_token ON refresh_tokens(session_id) WHERE state='pending';
CREATE TABLE market_quotes (instrument_id TEXT PRIMARY KEY,group_id TEXT NOT NULL,payload_json TEXT NOT NULL,retained SMALLINT NOT NULL DEFAULT 0 CHECK(retained IN (0,1)));
CREATE TABLE market_sessions (exchange TEXT PRIMARY KEY,payload_json TEXT NOT NULL,retained SMALLINT NOT NULL DEFAULT 0 CHECK(retained IN (0,1)));
CREATE TABLE collection_owner (id SMALLINT PRIMARY KEY CHECK(id=1),token TEXT NOT NULL);
